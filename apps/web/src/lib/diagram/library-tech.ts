import type { CellStyle } from '@maxgraph/core';
import type { LibGroup, LibItem } from './library';

const v = (
  id: string,
  nameId: string,
  nameEn: string,
  w: number,
  h: number,
  style: CellStyle,
  keys = '',
  value = '',
): LibItem => ({ id, name: { id: nameId, en: nameEn }, kind: 'vertex', w, h, style, keys, value });

const e = (id: string, nameId: string, nameEn: string, style: CellStyle, keys = ''): LibItem => ({
  id,
  name: { id: nameId, en: nameEn },
  kind: 'edge',
  w: 120,
  h: 0,
  style,
  keys,
});

/** Simbol: label di bawah gambar, tanpa isi. */
const sym = (shape: string, extra: CellStyle = {}): CellStyle => ({
  shape,
  verticalLabelPosition: 'bottom',
  verticalAlign: 'top',
  labelBackgroundColor: 'none',
  ...extra,
});
/** Ikon perangkat: label di bawah, isi putih. */
const dev = (shape: string): CellStyle => ({
  shape,
  verticalLabelPosition: 'bottom',
  verticalAlign: 'top',
  whiteSpace: 'wrap',
  fillColor: '#ffffff',
});

